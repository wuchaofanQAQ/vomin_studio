t = open(p, encoding="utf-8").read()

reps = [
("为每个资产产出「文字描述 + 提示词（不超过 50 字、单句、不分节）」，角色另产 6 模块档案供配音与演出；",
 "为每个资产产出一句可见描述（不超过 50 字），场景另带空间锚点；角色另产 6 模块档案供配音与演出；"),
("  → 每个资产：文字描述 + 提示词（≤50 字）\n",
 "  → 每个资产：一句可见描述（≤50 字，场景另带空间锚点）\n"),
("3. **提示词 ≤50 字**：单句、无【】分节、无小标题、不堆\"8K/超清/史诗/电影感\"；只写主体 + 关键外观 + 光线/景别。文字描述可以稍长，但只写看得见的东西。",
 "3. **只产描述，不产最终提示词**：每个资产一句可见描述（≤50 字），只写主体 + 关键外观 + 光线/景别；场景另起一行「空间锚点」。出图提示词由生成环节用描述 + 全局画风拼，本 skill 不写、也不写【】分节。"),
("### Step 4 — 写文字描述与提示词", "### Step 4 — 写文字描述"),
]

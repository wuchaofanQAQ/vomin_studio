# -*- coding: utf-8 -*-
p = r"skills\ai-drama-harness\references\data-contracts.md"
t = open(p, encoding="utf-8").read()

# 1) 骨架加道具锚点示例
t = t.replace(
"道具：【P01｜道具名：外形、尺度、数量】",
"道具：【P01｜道具名：外形、尺度、数量，{道具库：道具名}】")

# 2) 锚点表加道具库
t = t.replace(
"| `【P01｜行李箱：24 寸硬壳】` | 原样保留 | 无（道具没有库表） |",
"| `【P01｜行李箱：24 寸硬壳，{道具库：行李箱}】` | `【P01｜行李箱：24 寸硬壳】` | 道具参考图（道具库有该行且已出图） |\n| `【P01｜行李箱：24 寸硬壳】` | 原样保留 | 无（道具没有参考图） |")

# 3) 规则补一句
t = t.replace(
"规则：角色/场景**必须**带锚点且名称与库内逐字一致；锁定区有带图资产时**必须**写 `【参考图映射】`（图N 从 1 连续、顺序 = 锁定区出现顺序），否则模型无法对应参考图；带锚点的条目里不写补充内容（会被 `：】` 清理影响）；正文一律写\"编号+名称\"（`R01沈幼怡`），不写裸名。",
"规则：角色/场景**必须**带锚点且名称与库内逐字一致；道具**有图时**带 `{道具库：名}`，没图只写文字；锁定区有带图资产时**必须**写 `【参考图映射】`（图N 从 1 连续、顺序 = 锁定区出现顺序，带图道具也要列），否则模型无法对应参考图；补充内容写在锚点前（`24 寸硬壳，{道具库：行李箱}`），展开时 `：】`/`，】` 会自动收干净；正文一律写\"编号+名称\"（`R01沈幼怡`），不写裸名。")

# 4) JSON dependencies 加 props
t = t.replace(
'''    "new_scenes": [],
    "new_characters": []
  },''',
'''    "props": ["行李箱"],
    "new_scenes": [],
    "new_characters": [],
    "new_props": []
  },''')

open(p, "w", encoding="utf-8").write(t)
print("data-contracts updated")

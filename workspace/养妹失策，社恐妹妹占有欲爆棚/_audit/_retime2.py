if old05 not in t:
    old05 = """【镜头05｜[8s-10s]｜低头】
硬切特写固定机位，机位在她下颌下方略仰。【沈幼怡】的下巴与一小片湿透的裙领入画，一粒汗珠挂在颌尖、越坠越大；画面上缘留着她垂着的睫毛，没有抬起。【行李箱】的金属拉杆斜插在画左前景，地砖只作为虚焦的暖灰底色。汗珠离开下巴、坠到拉杆上砸开一小片深色。切在汗珠砸开、她的睫毛仍然没抬时。"""
new05 = """【镜头05｜[8s-9s]｜低头】
硬切特写固定机位，机位在她下颌下方略仰。【沈幼怡】的下巴与一小片湿透的裙领入画；颌尖那粒汗珠已经聚到最大、表面绷出一层亮，随即离开皮肤坠落，砸在画左前景的【行李箱】金属拉杆上炸开一小片深色。画面上缘留着她垂着的睫毛，全程没有抬起。切在汗珠炸开、水膜还在拉杆上反光时。"""

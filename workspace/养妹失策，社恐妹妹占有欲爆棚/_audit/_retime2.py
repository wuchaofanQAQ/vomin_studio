# -*- coding: utf-8 -*-
import re
p = r"C:\\Users\\Heart\\PycharmProjects\\vomin_studio\\workspace\\养妹失策，社恐妹妹占有欲爆棚\drafts\ep01_storyboard_v14.md"
t = open(p, encoding="utf-8").read()

# 1) 引号内不括号化资产名
def unquote(m):
    return "「" + m.group(1).replace("【", "").replace("】", "") + "」"
t = re.sub(r"「([^」]*)」", unquote, t)

# 2) 镜头05 压到 1 秒

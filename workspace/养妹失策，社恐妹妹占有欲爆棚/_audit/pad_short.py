src = open(f, encoding="utf-8").read()
lines = src.split("\n")
out, seg, i = [], 0, 0
while i < len(lines):
    ln = lines[i]
    mseg = re.match(r"^## 【第(\d+)段", ln)
    if mseg:
        seg = int(mseg.group(1))
    out.append(ln)
    m = re.match(r"^【镜头(\d+)｜", ln)
    if m and i + 1 < len(lines):
        no = int(m.group(1))
        if (seg, no) in NEW:
            out.append(NEW[(seg, no)]); i += 2; continue
    i += 1
open(f, "w", encoding="utf-8").write("\n".join(out))
print("补齐短镜:", len(NEW))

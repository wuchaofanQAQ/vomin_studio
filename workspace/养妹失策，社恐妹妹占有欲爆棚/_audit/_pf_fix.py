# -*- coding: utf-8 -*-
p = r"skills\drama-segment-generation\references\preflight-checklist.md"
t = open(p, encoding="utf-8").read()
pairs = [
("- [ ] **正文没有代词**（他/她/自己/前者/后者），所有人物指称都写成【资产名】",
 "- [ ] 正文人物指称写成 `编号+名称`（`R01沈幼怡`），不用裸名、不加【】；代词只在不产生歧义时用"),
("- [ ] 【本段资产锁定】按 场景/角色/道具/特效 分组，每条写成 `【名称：{表：行}】`，行标识与库主键逐字一致、与名称同名",
 "- [ ] 【本段资产锁定】按 场景/角色/群像/道具/动物/载具/特效 分组，每条写成 `【编号｜名称：{表：名}】`，名称与库主键逐字一致"),
("- [ ] 锁定引用的素材均已出图；未出图的只在\"待补资产\"，不进锁定块",
 "- [ ] 有图资产带锚点进锁定；有行无图标\"待出图\"（锚点可保留、不占图号）；库里没有的写 `待补：`，不带锚点"),
]
for old, new in pairs:
    c = t.count(old)
    print(c, old[:40])
    if c == 1:
        t = t.replace(old, new)
open(p, "w", encoding="utf-8").write(t)

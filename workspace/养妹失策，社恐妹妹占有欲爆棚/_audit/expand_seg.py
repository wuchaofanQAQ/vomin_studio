seg_split = re.split(r"(?m)^(## 【第\d+段.*?】)$", open(f, encoding="utf-8").read())
# seg_split: [pre, head1, body1, head2, body2, ...]
idx = 1 + (SEG - 1) * 2
assert seg_split[idx].startswith(f"## 【第{SEG:02d}段"), seg_split[idx][:20]
body = seg_split[idx + 1]

def repl(m):
    no = int(m.group(1))
    head = m.group(0)
    if no in NEW:
        return head + "\n" + NEW[no]
    return head

body = re.sub(r"^【镜头(\d+)｜\[[\d.]+s-[\d.]+s\]｜.+?】\n.+$", repl, body, flags=re.M)
seg_split[idx + 1] = body
open(f, "w", encoding="utf-8").write("".join(seg_split))
print(f"第{SEG:02d}段 已扩写")

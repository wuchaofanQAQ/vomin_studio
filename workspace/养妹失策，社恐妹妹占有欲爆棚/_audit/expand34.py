    mseg = re.match(r"^## 【第(\d+)段", ln)
    if mseg:
        seg = int(mseg.group(1))
    out.append(ln)
    m = re.match(r"^【镜头(\d+)｜", ln)
    if m and i + 1 < len(lines):
        no = int(m.group(1))
        tgt = SEG3 if seg == 3 else (SEG4 if seg == 4 else None)
        if tgt and no in tgt:
            out.append(tgt[no]); i += 2; continue
    i += 1

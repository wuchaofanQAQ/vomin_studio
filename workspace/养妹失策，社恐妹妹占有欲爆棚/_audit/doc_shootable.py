# -*- coding: utf-8 -*-
p = r"C:\Users\Heart\PycharmProjects\vomin_studio\skills\drama-segment-generation\SKILL.md"
t = open(p, encoding="utf-8").read()
if "小说式描写" not in t:
    anchor = "## 屏幕文字规则（手机/微信/打字）"
    add = '''## 小说式描写必须转成可拍动作

小说写"感受"，镜头只能拍"动作"。以下这类句子**一律不许出现在镜头正文里**：

| 小说写法 | 为什么不能拍 | 改成 |
|---|---|---|
| 字小得要凑近才看清 | 是叙述者的判断，不是画面 | 他把手机往眼前送了送，屏幕离鼻尖只剩一掌 |
| 她心里一酸 | 情绪不可见 | 她抿住嘴、鼻翼动了一下，睫毛垂下去 |
| 热气逼人 | 是体感 | 地面上的热气蒸得直抖、她的额头沁出汗 |
| 空气凝固了 | 比喻 | 两个人都没动，只剩空调外机在响 |

## 环境音必须有声源

「热浪的嗡鸣」「阳光的声音」这类**没有物理声源**的拟声一律不写。要写声音，先能指出是谁在响：

- ✅ 空调外机的低频嗡声、蝉声、电流底噪、冰箱压缩机、楼下小孩跑过、车轮压过井盖
- ❌ 热浪的嗡鸣、光的响声、沉默在响

画面里可以拍"热"，但声音只能来自具体物件。

'''
    t = t.replace(anchor, add + anchor)
    open(p, "w", encoding="utf-8").write(t)
    print("SKILL 已加两条规则")

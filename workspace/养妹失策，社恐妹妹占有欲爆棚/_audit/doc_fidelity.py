# -*- coding: utf-8 -*-
p = r"C:\Users\Heart\PycharmProjects\vomin_studio\skills\drama-segment-generation\SKILL.md"
t = open(p, encoding="utf-8").read()
if "情节零改动" not in t:
    anchor = "## 小说式描写必须转成可拍动作"
    add = '''## 情节零改动，情绪转动作

**事件、因果、台词、人物关系、数字（三个月房租、一个小时、两下门铃）一个字都不能改。** 能做的只有一件事：把原文里的情绪，翻译成观众看得见的动作。

| 原文写的情绪 | 不许做 | 要做的（可见动作） |
|---|---|---|
| 她在门口至少站了一个小时 | 加一句台词说"等了一小时" | 后背的裙子被汗浸出深色一片、发尾汗黏在颈侧 |
| 那手机比他三个月房租还贵 | 加旁白解释收入 | 三摄、钛边框反光、机身干净没有指纹 |
| 妈？她还知道自己是妈 | 加事件（摔手机） | 低声冷笑、牙关咬着、喉结滚一次 |
| 她局促 | 加台词"我紧张" | 双手交叠握手机、脚趾在瓷砖上缩 |
| 她被说中心事 | 加闪回 | 眨一次眼、呼吸停半拍、视线垂下去 |

**禁止清单**：新增物件（原厂膜、照片、信件）、新增事件（摔东西、接电话）、新增台词、改数字、改人物动机。

'''
    t = t.replace(anchor, add + anchor)
    open(p, "w", encoding="utf-8").write(t)
    print("SKILL 已加「情节零改动」规则")

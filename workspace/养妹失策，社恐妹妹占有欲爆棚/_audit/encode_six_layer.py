# -*- coding: utf-8 -*-
import re

# 1) prompt-density.md：写死「单镜六层」
p = r"C:\Users\Heart\PycharmProjects\vomin_studio\skills\drama-segment-generation\references\prompt-density.md"
t = open(p, encoding="utf-8").read()
if "## 单镜六层" not in t:
    add = '''## 单镜六层（缺一层就是废镜，正文 ≥120 字）

写每一镜前先回答六个问题，答不全就回去想，不要动笔：

| # | 层 | 要回答的问题 | 反例 → 正例 |
|---|---|---|---|
| 1 | **景别** | 从多远看？ | 「近景」→「门外机位、与【陈诚】眼平齐的近景」 |
| 2 | **调度** | 人和机位怎么动？ | 「他走到窗边」→「镜头随【陈诚】横移半步，他经过【沈幼怡】身边时脚步慢半拍，走过去才加快」 |
| 3 | **表演** | 他在忍什么？身体哪里泄漏？ | 「他皱眉」→「拇指按了两次没按准，第三次才亮；指甲压进掌心压出四个印」 |
| 4 | **环境** | 空间里有什么在动？ | 热浪把墙线晃软、地砖被晒出白亮、柜子轮廓浮在暗里 |
| 5 | **环境音** | 这一镜观众听到什么？ | 门轴先响、水声、杯底磕茶几、话筒漏音、冰箱嗡鸣、忙音、风扇声 |
| 6 | **光影** | 光从哪来、怎么变？ | 「逆光勾出下颌线」「屏光从下往上照鼻底」「门合上把走廊的白切掉一半」 |

**收尾**：写清切在哪一拍（「切在铃声尾音还没散」），不要写「落幅停在…」这种模板句。

### 三条禁令

1. **禁止只写动作**：只有「谁做了什么」的镜头＝废镜，必须带表演与环境。
2. **禁止只写前中后景**：三层是构图，不是全部；缺环境音与光影同样不合格。
3. **禁止一镜同构**：连续三镜以上用同一句式（如都以「切镜头，X景，」开头）视为偷懒，必须换写法。

'''
    i = t.index("##")
    t = t[:i] + add + t[i:]
    open(p, "w", encoding="utf-8").write(t)
    print("density：六层已写入")

# 2) self-check.md：加六层核对
p2 = r"C:\Users\Heart\PycharmProjects\vomin_studio\skills\drama-segment-generation\references\self-check.md"
s = open(p2, encoding="utf-8").read()
if "六层逐镜过" not in s:
    add2 = '''## 六层逐镜过（每镜都要能答出来）

- [ ] 景别＋机位：从多远、站哪儿看
- [ ] 调度：人和机位这一镜怎么动
- [ ] 表演：他在忍什么，身体哪一处泄漏了
- [ ] 环境：空间里有什么在动（热浪/灰尘/窗帘/地板）
- [ ] 环境音：这一镜能听见什么
- [ ] 光影：光从哪来、和上一镜比变了什么
- [ ] 切点：切在哪一拍（不是「落幅停在…」）

'''
    s = s.replace("## 第一轮", add2 + "## 第一轮", 1)
    open(p2, "w", encoding="utf-8").write(s)
    print("self-check：六层已加")

# -*- coding: utf-8 -*-
p = r"C:\Users\Heart\PycharmProjects\vomin_studio\skills\drama-segment-generation\SKILL.md"
t = open(p, encoding="utf-8").read()

start = t.index("### 关于资产库的三条铁律")
end = t.index("### 理解在前，镜头在后")
new = '''### 关于资产图与备注（三条）

1. **图是外观事实，但图只是一张静帧。** 长相、服装、家具的**样子**以图为准；但**图里的机位、焦段、构图不是本段的机位**——不能因为参考图是广角全景，就把整段都写成广角。外观照图，镜头照戏。
2. **备注是参考，不是抄写模板。** 备注（反打关系、同源图、近中远景）大概率是对的，用来**校正你对空间的理解**；但它不是逐字照搬的台词。发现备注与图或剧本对不上时，以你自己的空间判断 + 图为准，并在交付说明里写出依据。
3. **先建立对场景的完整理解，再动镜头。** 写段之前在心里（或草稿上）过一遍：
   - 门在哪、窗在哪、光从哪来、有几条可行走的路线
   - 主要家具的朝向，人坐下/站起/转身会挡住什么
   - 轴线在哪一侧，哪几个机位是同一侧、哪个会跳轴

   对不上、或图里看不全的，标 `待补` 或先问，**不许凭一张图猜空间关系**。

'''
t = t[:start] + new + t[end:]

old2 = "外观一律**以真实图片为准**（`描述` 只是当初的出图提示词，会跑偏）；`备注` 里的反打关系、同源图、近/中/远景必须照它写。"
new2 = "外观**以真实图片为准**（`描述` 只是当初的出图提示词，会跑偏）；`备注` 是参考、大概率正确，用来校正空间理解，**不是照抄模板**；本段的机位与构图由戏决定，不由参考图决定。"
assert t.count(old2) == 1
t = t.replace(old2, new2)
open(p, "w", encoding="utf-8").write(t)
print("规则已改为「理解优先」")


# -*- coding: utf-8 -*-
p = r"skills\drama-segment-generation\references\prompt-density.md"
t = open(p, encoding="utf-8").read()
add = """

## 九、两条最容易写错的硬约束

### 1. 景别决定可见集合

- **近景**只装得下头肩，**特写**只装得下局部（眼睛、手指、汗珠、屏幕）。
- 近景/特写的后景只能写**光、虚焦色块、同一个人身上的部位**；写「地砖/走廊纵深/厨房/客厅」就是拍不出来。
- 要写全「前景—中景—后景」三层，就换**中景/中全景/全景**。

| 错误 | 为什么错 | 改法 |
|---|---|---|
| 近景 + 后景是地砖 | 站着的近景看不到脚底 | 后景改「门外过曝的白」或「虚焦的走廊」 |
| 近景里写「汗珠坠到行李箱拉杆」 | 拉杆在她腰以下，近景不入画 | 改成**特写**：下巴+拉杆+虚焦地砖，拍那滴汗 |
| 特写手机 + 后景是地砖 | 手机举在胸前，背景是衣料/走廊 | 后景改「她衣料的暗部」 |

### 2. 动作句必须有执行人

「门从内侧拉开」「箱子被拎起」这类没有主语的句子，模型会让物体**自己动**。

- ✗ `门从内侧拉开，【陈诚】站在门内`
- ✓ `【陈诚】右手先拧动门把，把门从内侧拉开；他站在门内`

写动作时固定三件事：**谁**（【名称】）+ **哪个部位**（右手/双手/肩膀）+ **怎么发力**（拧、拽、推、拎）。
"""
assert "## 九、两条最容易写错的硬约束" not in t
open(p, "w", encoding="utf-8").write(t + add)
print("density rules added")

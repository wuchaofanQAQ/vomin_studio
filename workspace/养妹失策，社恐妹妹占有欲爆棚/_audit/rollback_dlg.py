n = 0
for i, ln in enumerate(lines):
    m = re.match(r"^(\[[\d.]+s-[\d.]+s\]，)(【[^】]+】)（[^）]*）：「(.+)」$", ln)
    if not m:
        continue
    quote = m.group(3)
    if quote in MAP:
        who, cue, orig = MAP[quote]
        lines[i] = f"{m.group(1)}{who}（{cue}）：「{orig}」"
        n += 1
open(f, "w", encoding="utf-8").write("\n".join(lines))
print("回滚台词条数", n)

# -*- coding: utf-8 -*-
p = r"skills\novel-to-drama\references\adaptation-rules.md"
t = open(p, encoding="utf-8").read()

old4 = '''## 四、对白

- 保留原话的**信息和语气**，改成口语：短句、断句、一句一个信息点
- 一句台词尽量不超过 20 字；长段独白拆成与动作交错的多句
- 不替角色编造原文没有的关键信息；过渡性寒暄可适度删
- 说话人每句都要标出，供下游绑定角色与音色'''
new4 = '''## 四、对白

- **引号里的台词逐字进剧本**：不改写、不合并、不"翻译"成更顺口的版本；原文已经口语，不需要你再口语化
- 只有把**叙述**转成台词时，才允许短句、断句、一句一个信息点
- 一句台词超过 20 字可以拆成两句，但字不能丢
- 不替角色编造原文没有的关键信息；过渡性寒暄可删，删了要在删减清单里写
- 说话人每句都要标出，供下游绑定角色与音色

```text
❌ 原文「你爸呢？」→ 剧本「你爸人呢？」（改了字）
✅ 原文「你爸呢？」→ 剧本「你爸呢？」
```'''
assert t.count(old4) == 1
t = t.replace(old4, new4)

old5 = '''**可删**：重复的心理描写、与主线无关的景物铺陈、冗长的背景介绍、已被动作取代的转述。'''
new5 = '''**可删**：重复的心理描写、与主线无关的景物铺陈、冗长的背景介绍、已被动作取代的转述。

**不许吞掉判断句**（真实事故）：

```text
原文：「靠！」陈诚低骂一声，听不懂人话是吧？这天再晒下去真会出人命！
❌ 剧本只留：陈诚（低骂）：靠。  → 判断和动机整段消失
✅ 剧本应写：
   陈诚（低骂）：靠。
   陈诚（OS）：听不懂人话是吧？这天再晒下去真会出人命。
```

判据：一句话里只要含**判断、动机、信息差、反问**，就不能用"动作已经表达了"当理由删掉；动作替代不了"他为什么这么做"。'''
assert t.count(old5) == 1
t = t.replace(old5, new5)
open(p, "w", encoding="utf-8").write(t)
print("adaptation-rules updated")

lines = open(f, encoding="utf-8").read().split("\n")
out, seg, i = [], 0, 0
while i < len(lines):
    ln = lines[i]
    m = re.match(r"^## 【第(\d+)段", ln)
    if m: seg = int(m.group(1))
    out.append(ln)
    ms = re.match(r"^【镜头(\d+)｜", ln)
    if ms and i + 1 < len(lines):
        no = int(ms.group(1))
        tgt = NEW3 if seg == 3 else (NEW4 if seg == 4 else None)
        if tgt and no in tgt:
            out.append(tgt[no]); i += 2; continue
    i += 1
open(f, "w", encoding="utf-8").write("\n".join(out))

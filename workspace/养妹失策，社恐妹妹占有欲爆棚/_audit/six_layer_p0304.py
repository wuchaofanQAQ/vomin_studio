src = open(f, encoding="utf-8").read()
lines = src.split("\n")
out, seg, i = [], 0, 0
while i < len(lines):
    ln = lines[i]
    m = re.match(r"^## 【第(\d+)段", ln)
    if m: seg = int(m.group(1))
    out.append(ln)
    ms = re.match(r"^【镜头(\d+)｜\[([\d.]+)s-([\d.]+)s\]｜(.+?)】$", ln)
    if ms and i + 1 < len(lines):
        no = int(ms.group(1))
        tgt = S3 if seg == 3 else (S4 if seg == 4 else None)
        if tgt and no in tgt:
            t, body = tgt[no]
            out[-1] = f"【镜头{no:02d}｜[{ms.group(2)}s-{ms.group(3)}s]｜{t}】"
            out.append(body); i += 2; continue
    i += 1
open(f, "w", encoding="utf-8").write("\n".join(out))

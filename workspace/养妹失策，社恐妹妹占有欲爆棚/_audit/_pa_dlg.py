p = r"skills\drama-segment-generation\references\project-adaptation.md"
t = open(p, encoding="utf-8").read()

old4 = t[t.index("## 4. 台词行"):t.index("## 5. 编号登记表")]
new4 = '''## 4. 台词行：直接写在发声位置（4.2）

```text
00:05-00:06，R02陈诚（压着火、短促地说）：『你爸呢？』
00:09-00:10.5，R02陈诚画外音（画右门板后、压低地说）：『谁啊？』
```

- 行首 `起-止` 是时间窗，必须落在所在镜头的窗口内；
- 说话者写 `编号+名称`，括号里必须有"说"；
- 画外音加"画外音"并把方向（画左/画右/画上/画下）写进括号；
- 台词用 `『』` 括起，逐字，不改写、不合并、不删；每句只在真正发声的位置出现一次；
- **本项目不做 TTS**：对白由视频模型原生发声。需要固定音色时，在锁定区该角色条目后加 `音频参考：{音色库：音色名}`，CLI 收集音色库文件作为 `reference_audio` 传给模型。

'''
t = t.replace(old4, new4)

t = t.replace("# 3) 配音先行（便宜，先听节奏与时长）\npython cli.py generate $WS --tts-only\n\n# 4) 出片（花预算，需再次确认）\npython cli.py generate $WS\n\n# 5) 回写状态",
              "# 3) 出片（花预算，需再次确认；对白由模型原生发声，不需要先配音）\npython cli.py generate $WS\n\n# 4) 回写状态")

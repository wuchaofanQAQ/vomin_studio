# ---- 切成段 -> 镜，逐镜替换 ----
seg_spans = [(m.start(), m.group(1)) for m in re.finditer(r"【第0?(\d+)段｜", t)]
seg_spans.append((len(t), None))
out, done = [], set()
for i in range(len(seg_spans) - 1):
    s, no = seg_spans[i]
    e = seg_spans[i + 1][0]
    block = t[s:e]
    shots = [(m.start(), m.group(1)) for m in re.finditer(r"【镜头(\d+)｜", block)]
    if not shots:
        out.append(block); continue
    shots.append((len(block), None))
    head = block[:shots[0][0]]
    out.append(head)
    for j in range(len(shots) - 1):
        ss, sh = shots[j]
        ee = shots[j + 1][0]
        seg_txt = block[ss:ee]
        key = (int(no), int(sh))
        for old, new in EDITS.get(key, []):
            n = seg_txt.count(old)
            if n != 1:
                print(f"  !! 段{no} 镜{sh}：「{old}」命中 {n} 次")
                sys.exit(1)
            seg_txt = seg_txt.replace(old, new, 1)
        done.add(key)
        out.append(seg_txt)

missing = set(EDITS) - done
if missing:
    print("  !! 未命中镜：", sorted(missing)); sys.exit(1)

new_text = "".join(out)
io.open(P, "w", encoding="utf-8").write(new_text)
print(f"已改 {len(EDITS)} 镜，替换 {sum(len(v) for v in EDITS.values())} 处；总长 {len(new_text)}")
